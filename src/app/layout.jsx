import { JetBrains_Mono } from "next/font/google";
import "./globals.css";
import Header from "../components/Header";
import PageTransition from "@/components/PageTransition";
import StairTransition from "@/components/StairTransition";
import Script from "next/script"; // 1. Adım: Next.js Script bileşenini import ettik

const jetbrainsMono = JetBrains_Mono({
  subsets: ["latin"],
  weight: ["100", "200", "300", "400", "500", "600", "700", "800"],
  variable: '--font-jetbrainsMono',
});

export const metadata = {
  title: "Taha Gülbaz",
  description: "Generated by create next app",
};

// ... diğer importlar aynı kalacak ...

export default function RootLayout({ children }) {
  const gaId = process.env.NEXT_PUBLIC_GA_ID; // Değişkeni tanımladık

  return (
    <html lang="en">
      <head>
        {/* Google Analytics kodunu dinamik hale getirdik */}
        {gaId && (
          <>
            <Script
              src={`https://www.googletagmanager.com/gtag/js?id=${gaId}`}
              strategy="afterInteractive"
            />
            <Script id="google-analytics" strategy="afterInteractive">
              {`
                window.dataLayer = window.dataLayer || [];
                function gtag(){dataLayer.push(arguments);}
                gtag('js', new Date());

                gtag('config', '${gaId}');
              `}
            </Script>
          </>
        )}
      </head>
      <body className={jetbrainsMono.variable}>
        <Header />
        <StairTransition></StairTransition>
        <PageTransition>{children}</PageTransition>
      </body>
    </html>
  );
}